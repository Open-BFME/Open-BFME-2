// game.dat has no string naming a twiddler and no unit in this tree uses one, so the Zero Hour
// class is gone. Its one row rests here. A virtual's address is a call thunk, so a direct call
// from a function nothing runs makes this unit emit the inline body, and inline_depth keeps
// the call out of line.
#pragma inline_depth(0)
static void callIndirectClassId(TwiddlerClass *twiddler)
{
	twiddler->TwiddlerClass::Set_Indirect_Class_ID(0);
}
#pragma inline_depth()

extern const void *const g_twiddlerRowAnchor = (const void *)&callIndirectClassId;
