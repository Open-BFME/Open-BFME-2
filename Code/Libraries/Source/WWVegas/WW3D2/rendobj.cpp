void RenderObjClass::Set_Force_Visible(int onoff)
{
	if ((onoff != 0) != (Is_Force_Visible() != 0)) {
		Bits ^= IS_FORCE_VISIBLE;
		if (Scene != NULL) {
			if (onoff) {
				Scene->Register(this, (SceneClass::RegType)4);
			} else {
				Scene->Unregister(this, (SceneClass::RegType)4);
			}
		}
	}
}

