//
// ?AdaptiveDeltaMotionChannelClass::Get_QuatVector present-unmatched
Quaternion AdaptiveDeltaMotionChannelClass::Get_QuatVector(float32 frame)
{

	uint32 frame1 = frame;
	uint32 frame2 = frame1+1;
	float ratio = frame - frame1;

	Quaternion q1(1);
	q1.Set( getframe(frame1, 0),
			  getframe(frame1, 1),
			  getframe(frame1, 2),
			  getframe(frame1, 3) );

	Quaternion q2(1);

	q2.Set( getframe(frame2, 0),
			  getframe(frame2, 1),
			  getframe(frame2, 2),
			  getframe(frame2, 3) );


	Quaternion q(1);

	Fast_Slerp(q, q1, q2, ratio);

	return( q );

}

