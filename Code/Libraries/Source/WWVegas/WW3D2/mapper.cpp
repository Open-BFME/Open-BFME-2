inline void GridTextureMapperClass::Reset(void)
{
	Remainder = 0;
	if (Sign >= 0) {
		CurrentFrame = Offset;
	} else {
		CurrentFrame = (LastFrame - 1) - Offset;
	}
	LastUsedSyncTime = WW3D::Get_Sync_Time();
}

