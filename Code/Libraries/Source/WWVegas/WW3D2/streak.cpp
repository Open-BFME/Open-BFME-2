void StreakLineClass::Set_Widths( unsigned int num_points, float *widths )
{
	if (num_points < 2 || !widths) {
		WWASSERT(0);
		return;
	}

	PointWidths.Delete_All();
	for (unsigned int i=0; i<num_points; i++) {
		PointWidths.Add(widths[i],num_points);
	}

}

