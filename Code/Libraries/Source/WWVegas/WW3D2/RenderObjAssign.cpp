#include "rendobj.h"
#include "aabox.h"

typedef char RenderObjSizeMatchesRetail[(sizeof(RenderObjClass) == 0xC4) ? 1 : -1];

// The retail assignment copies transform storage and its identity byte after
// the visibility/collision virtuals. Both indexed-factor calls use this object
// as the receiver; the loop is not a copy from that.
RenderObjClass &RenderObjClass::operator=(const RenderObjClass &that)
{
    if (this != &that) {
        Set_Hidden(that.Is_Hidden());
        Set_Animation_Hidden(that.Is_Animation_Hidden());
        Set_Force_Visible(that.Is_Force_Visible());
        Set_Collision_Type(that.Get_Collision_Type());
        Transform = that.Transform;
        IsTransformIdentity = that.IsTransformIdentity;
        for (int i = 0; i < 2; ++i) {
            _bfme_set_indexed_factor(i, _bfme_get_indexed_factor(i));
        }
    }
    return *this;
}
